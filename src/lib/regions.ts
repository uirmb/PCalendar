function coordinate(value: string): number {
  const sign = value[0] === '-' ? -1 : 1;
  const digits = value.slice(1);
  const degreeDigits = digits.length % 2 === 0 ? 2 : 3;
  const degrees = Number(digits.slice(0, degreeDigits));
  const minutes = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const seconds = Number(digits.slice(degreeDigits + 2) || 0);
  return sign * (degrees + minutes / 60 + seconds / 3600);
}

export function getChineseCityId(location: Pick<GeographicLocation, 'province' | 'code' | 'name'>, occurrence = 0): string {
  const base = `cn:${location.province}:${location.code}:${location.name}`;
  return occurrence ? `${base}#${occurrence + 1}` : base;
}

