/** 我只把明确的旧地区名称映射到代表城市，不从 UTC 偏移猜国家。 */
export function getLegacyRegion(name: string): RegionCity | undefined {
  if (name === '中国') return defaultChina;
  const timezoneId = legacyZones[name];
  if (timezoneId) return representatives.find((city) => city.timezoneId === timezoneId);
  const country = legacyCountries[name] ?? countries.find((item) => item.name === name)?.code;
  return country ? getDefaultCity(country) : undefined;
}

export function resolveWeekStart(settings: Pick<Preferences, 'countryCode' | 'weekStart' | 'weekStartMode'>): Weekday {
  return settings.weekStartMode === 'custom' ? settings.weekStart : getCountry(settings.countryCode)?.weekStart ?? 1;
}
export function uses12HourClock(settings: Pick<Preferences, 'countryCode' | 'clockFormat'>): boolean {
  return settings.clockFormat === '12' || (settings.clockFormat === 'auto' && getCountry(settings.countryCode)?.clockFormat === '12');
}
